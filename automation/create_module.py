def generate_module_config(config: ModuleConfig) -> str:
    """Generate module_config.json metadata file."""
    return json.dumps({
        "name": config.module_id,
        "class_name": config.class_name,
        "package_name": config.package_name,
        "version": config.version,
        "template": config.template,
        "routes": config.routes,
        "gates": config.gates,
        "generated_at": "2025-01-01T00:00:00Z",
    }, indent=2)


def create_module_structure(
    config: ModuleConfig, output_dir: Path, dry_run: bool = False
) -> list[Path]:
    """Create complete module structure.

    Args:
        config: Module configuration
        output_dir: Output directory for the module
        dry_run: If True, don't actually create files

    Returns:
        List of created file paths
    """
    module_dir = output_dir / config.name
    lib_dir = module_dir / "lib" / "src"
    screens_dir = lib_dir / "screens"
    widgets_dir = lib_dir / "widgets"
    services_dir = lib_dir / "services"
    test_dir = module_dir / "test"
    l10n_dir = module_dir / "lib" / "l10n"

    created_files: list[Path] = []

    if not dry_run:
        # Create directories
        for dir_path in [lib_dir, screens_dir, widgets_dir, services_dir, test_dir, l10n_dir]:
            dir_path.mkdir(parents=True, exist_ok=True)

    # Generate files based on template
    template_config = TEMPLATES.get(config.template, TEMPLATES["minimal"])

    files_to_generate: dict[Path, str] = {}

    if "module_descriptor" in template_config["files"]:
        files_to_generate[lib_dir.parent / f"{config.module_id}_module.dart"] = generate_module_descriptor(config)

    if "list_screen" in template_config["files"]:
        files_to_generate[screens_dir / f"{config.module_id}_list_screen.dart"] = generate_list_screen(config)

    if "detail_screen" in template_config["files"]:
        files_to_generate[screens_dir / f"{config.module_id}_detail_screen.dart"] = generate_detail_screen(config)

    if "form_screen" in template_config["files"]:
        files_to_generate[screens_dir / f"{config.module_id}_form_screen.dart"] = generate_form_screen(config)

    if "service" in template_config["files"]:
        files_to_generate[services_dir / f"{config.module_id}_service.dart"] = generate_service(config)

    # Always generate these
    files_to_generate[module_dir / "pubspec.yaml"] = generate_pubspec(config)
    files_to_generate[module_dir / "README.md"] = generate_readme(config)
    files_to_generate[module_dir / "module_config.json"] = generate_module_config(config)

    if not dry_run:
        for file_path, content in files_to_generate.items():
            with open(file_path, "w", encoding="utf-8") as f:
                f.write(content)

    created_files.extend(files_to_generate.keys())
    return created_files


def main(argv: Sequence[str] | None = None) -> int:
    """Main entry point for CLI."""
    parser = argparse.ArgumentParser(
        prog="create-module",
        description="Generate a new Flutter module for the wrapper app",
    )
    parser.add_argument(
        "--name",
        required=True,
        help="Module name (e.g., module_blog, inventory)",
    )
    parser.add_argument(
        "--template",
        choices=list(TEMPLATES.keys()),
        default="minimal",
        help="Module template to use",
    )
    parser.add_argument(
        "--routes",
        help="Comma-separated routes (e.g., '/blog,/blog/:id')",
    )
    parser.add_argument(
        "--gates",
        help="Comma-separated feature gates (e.g., 'blog.view,blog.create')",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("packages"),
        help="Output directory for the module (default: packages/)",
    )
    parser.add_argument(
        "--version",
        default="1.0.0",
        help="Module version (default: 1.0.0)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show what would be created without creating files",
    )
    parser.add_argument(
        "--list-templates",
        action="store_true",
        help="List available templates",
    )

    args = parser.parse_args(argv)

    # List templates
    if args.list_templates:
        print("\nAvailable Templates:")
        print("-" * 50)
        for name, info in TEMPLATES.items():
            print(f"\n{name}:")
            print(f"  {info['description']}")
            print(f"  Files: {', '.join(info['files'])}")
        return 0

    # Validate module name
    if not args.name.startswith("module_") and not args.name.replace("_", "").isalnum():
        print(f"Error: Invalid module name '{args.name}'", file=sys.stderr)
        print("Module name should be snake_case and contain only letters, numbers, and underscores.", file=sys.stderr)
        return 1

    # Ensure name has module_ prefix
    name = args.name if args.name.startswith("module_") else f"module_{args.name}"

    # Parse routes and gates
    routes = [r.strip() for r in args.routes.split(",")] if args.routes else []
    gates = [g.strip() for g in args.gates.split(",")] if args.gates else []

    config = ModuleConfig(
        name=name,
        template=args.template,
        routes=routes,
        gates=gates,
        version=args.version,
    )

    # Check if module already exists
    module_dir = args.output / name
    if module_dir.exists() and not args.dry_run:
        print(f"Error: Module directory already exists: {module_dir}", file=sys.stderr)
        return 1

    # Create module
    if args.dry_run:
        print(f"\n[Dry Run] Would create module: {name}")
        print(f"Location: {module_dir}")
        print(f"Template: {args.template}")
        print(f"Routes: {routes}")
        print(f"Gates: {gates}")
        return 0

    try:
        created_files = create_module_structure(config, args.output)

        print(f"\n✓ Created module: {name}")
        print(f"Location: {module_dir}")
        print(f"Template: {args.template}")
        print(f"\nFiles created:")
        for file_path in sorted(created_files):
            print(f"  {file_path.relative_to(args.output)}")

        print(f"\nNext steps:")
        print(f"  1. cd {module_dir}")
        print(f"  2. Implement the TODOs in the generated files")
        print(f"  3. Add to apps/wrapper_app/lib/module_registry.dart:")
        print(f"     {config.class_name}(),")
        print(f"  4. flutter test")

        return 0

    except Exception as e:
        print(f"Error creating module: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
