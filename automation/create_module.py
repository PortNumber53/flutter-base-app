@dataclass
class ModuleConfig:
    """Configuration for module generation."""

    name: str
    template: str
    routes: list[str]
    gates: list[str]
    version: str = "1.0.0"

    @property
    def module_id(self) -> str:
        """Extract module ID from name (e.g., module_blog -> blog)."""
        return self.name.replace("module_", "")

    @property
    def class_name(self) -> str:
        """Generate PascalCase class name."""
        parts = self.module_id.split("_")
        return "".join(p.capitalize() for p in parts) + "Module"

    @property
    def package_name(self) -> str:
        """Generate Dart package name."""
        return self.name.lower().replace("_", "_")


def to_pascal_case(s: str) -> str:
    """Convert snake_case to PascalCase."""
    return "".join(word.capitalize() for word in s.split("_"))


def to_camel_case(s: str) -> str:
    """Convert snake_case to camelCase."""
    parts = s.split("_")
    return parts[0] + "".join(word.capitalize() for word in parts[1:])


def generate_module_descriptor(config: ModuleConfig) -> str:
    """Generate the main module descriptor file."""
    route_definitions = []
    nav_entries = []

    for i, route in enumerate(config.routes):
        # Parse route pattern
        if ":" in route:
            # Parameterized route
            param_name = route.split(":")[-1].rstrip("/")
            route_clean = route.replace(f":{param_name}", f"{{${to_camel_case(param_name)}}}")
        else:
            route_clean = route
            param_name = None

        screen_class = f"{to_pascal_case(config.module_id)}{to_pascal_case(route.split('/')[-1].split(':')[0])}Screen"

        route_definitions.append(f'''    RouteDefinition(
      route: '{route_clean}',
      builder: (_) => const {screen_class}(),
      gates: {config.gates if config.gates else "const []"},
    ),''')

        if i == 0:  # Add navigation entry for first route
            nav_entries.append(f'''    MenuEntry(
      label: '{to_pascal_case(config.module_id)}',
      route: '{route_clean}',
      iconName: 'folder',
      gates: {config.gates if config.gates else "const []"},
    ),''')

    routes_str = "\n".join(route_definitions) if route_definitions else "    // Add routes here"
    nav_str = "\n".join(nav_entries) if nav_entries else "    // Add navigation entries here"

    return f'''import 'package:module_sdk/module_sdk.dart';

/// {to_pascal_case(config.module_id)} module for the wrapper app.
///
/// Generated by: automation.create-module
/// Version: {config.version}
class {config.class_name} extends ModuleDescriptor {{
  @override
  String get id => '{config.module_id}';

  @override
  String get version => '{config.version}';

  @override
  String get displayName => '{to_pascal_case(config.module_id)}';

  @override
  List<FeatureKey> get requiredFeatures => {config.gates if config.gates else "const []"};

  @override
  List<RouteDefinition> get routes => [
{routes_str}
  ];

  @override
  List<MenuEntry> get navigation => [
{nav_str}
  ];

  @override
  Future<void> initialize(ModuleContext ctx) async {{
    // Module initialization
    ctx.analytics.track('{config.module_id}_module_initialized');
  }}
}}
'''


